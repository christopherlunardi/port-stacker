# Builds game/src/js/09c-studio.js: the Idle Looping Studios intro (Chris picked the stepped logo, D with the scatter text and the sub
# glide sound, then fade to black, 2026-11-10) as the game plays it before the title. The drawing is intro.js itself, wrapped so its names stay its own;
# the stepped logo's pieces (logo2/) and the sound (sub glide, rendered by sounds_d.py) are packed in.
# usage: python3 -I art/intro/build_game.py SOUND.wav     (then build the game as usual)
import base64, json, pathlib, subprocess, sys, tempfile

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'game' / 'src' / 'js' / '09c-studio.js'
wav = pathlib.Path(sys.argv[1])
L = HERE / 'logo2'

with tempfile.TemporaryDirectory() as td:
    mp3 = pathlib.Path(td) / 's.mp3'
    subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(wav), '-codec:a', 'libmp3lame', '-b:a', '128k', str(mp3)], check=True)
    snd = base64.b64encode(mp3.read_bytes()).decode()

b64 = lambda p: 'data:image/png;base64,' + base64.b64encode(p.read_bytes()).decode()
assets = {
    'wave': json.loads((L / 'wave.json').read_text()),
    'roll': json.loads((L / 'roll.json').read_text()),
    'logo': json.loads((L / 'logo.json').read_text()),
    'text': b64(L / 'text.png'),
    'art': b64(L / 'art.png'),
    'snd': 'data:audio/mpeg;base64,' + snd,
}
src = (HERE / 'intro.js').read_text()
# the fade-out draws the landed logo each frame: from the held copy (below) instead of drawing it all again
FADE = "    draw(ctx, 'D', end);\n    ctx.fillStyle = '#000';"
assert src.count(FADE) == 1, 'drawOutro fade changed: update build_game.py'
src = src.replace(FADE, "    drawHeld(ctx, end);\n    ctx.fillStyle = '#000';")
OUT.write_text(
    '// GENERATED by art/intro/build_game.py from art/intro/intro.js and art/intro/logo2/: edit those and rebuild, not this file.\n'
    '// The Idle Looping Studios intro before the title (Chris 2026-11-10): the stepped logo, D, scatter text, sub glide. 09d-studio.js plays it.\n'
    'const STUDIO = (() => {\n'
    + src
    + '\nconst A = ' + json.dumps(assets, separators=(',', ':')) + ';\n'
    '  let ready = false;\n'
    '  // from STILL on, the picture no longer changes (checked frame by frame, 2026-11-10): it is drawn once and held, so the hold and the\n'
    '  // fade-out cost a copy a frame, not the whole drawing (the Retroid 2S was slow on it)\n'
    "  const STILL = 1.7; let HELD = null;\n"
    "  function drawHeld(ctx, t) { if (t < STILL) return draw(ctx, 'D', t); if (!HELD) { HELD = document.createElement('canvas'); HELD.width = W; HELD.height = H; draw(HELD.getContext('2d'), 'D', OPTS.D.len + 1.0); } ctx.drawImage(HELD, 0, 0); }\n"
    '  // draws a few frames off screen first, so the pieces it works out once (specks, columns, lines) are ready before it plays: on a\n'
    '  // phone the first frames otherwise stalled and the picture fell behind its sound\n'
    "  function warm() { try { const c = document.createElement('canvas'); c.width = W; c.height = H; const g = c.getContext('2d'); for (const t of [0.1, 0.9, 1.2, 1.4]) draw(g, 'D', t); drawHeld(g, STILL); } catch (e) {} }\n"
    '  function load(done) {\n'
    "    WAVE = A.wave; useLogo(A.logo); ROLL = A.roll; DSTYLE = 'scatter';\n"
    '    let n = 2;\n'
    '    const ok = () => { if (--n === 0) { warm(); ready = true; if (done) done(); } };\n'
    '    TEXT = new Image(); ART = new Image();\n'
    '    TEXT.onload = ART.onload = ok; TEXT.onerror = ART.onerror = ok;\n'
    '    TEXT.src = A.text; ART.src = A.art;\n'
    '  }\n'
    "  return { load, ready: () => ready, draw: drawHeld, len: OPTS.D.len + 1.0, W, H, snd: A.snd, outro: (ctx, u) => drawOutro(ctx, 'fade', u), outroLen: OUTROS.fade.dur };\n"
    '})();\n'
)
print(OUT, OUT.stat().st_size, 'bytes')
